/** e.g. "The Sacred Miracle of Barbarika's Sacrifice" -> "the-sacred-miracle-of-barbarikas-sacrifice" */
export function slugify(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
}
